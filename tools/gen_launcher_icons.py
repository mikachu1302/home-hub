#!/usr/bin/env python3
"""Generates the launcher icons (docs/DESIGN.md, "App icon"): one per palette in Theme.kt, a lowercase "h" in CRT
pixels in the palette's "alive" colour with a cursor block in its action colour, on the palette's background; a white
monochrome version for themed icons; and the manifest aliases that switch between them (ui/LauncherIcon.kt).
The same approach as tv-remote's tools/gen_launcher_icons.py.
Run from the repository root after changing a palette: python3 tools/gen_launcher_icons.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP = ROOT / "android/app/src/main"
THEME = APP / "java/io/github/mikachu1302/homehub/ui/Theme.kt"
RES = APP / "res"
MANIFEST = APP / "AndroidManifest.xml"
DEFAULT = "neon"

PALETTE = re.compile(
    r'Palette\(\s*"(\w+)", "([^"]+)", bg = c\(0x(\w+)\), surface = c\(0x(\w+)\), border = c\(0x(\w+)\),\s*'
    r"text = c\(0x(\w+)\), dim = c\(0x(\w+)\), primary = c\(0x(\w+)\), action = c\(0x(\w+)\),\s*"
    r"soft = c\(0x(\w+)\), warn = c\(0x(\w+)\),",
    re.S,
)

# The "h" on a pixel grid: one cell is 7 units, a pixel 6 (a 1-unit gap, like a CRT's dot mask). Columns 0..6, rows
# 0..8 from (30, 22) on the 108 x 108 canvas: the stem, the shoulder, the right leg, and the cursor block at the foot.
UNIT, PIXEL, ORIGIN = 7, 6, (30, 22)
STEM = [(0, r) for r in range(9)]
SHOULDER = [(c, 4) for c in range(1, 4)]
LEG = [(4, r) for r in range(5, 9)]
CURSOR = (6, 8)
# Launchers show only the central ~66 of the 108 units through their mask: scaled about the centre so the farthest
# pixel corner stays inside (about 31 units from the centre).
SCALE, SHIFT_Y = 0.8, 1

HEAD = """<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <!-- generated by tools/gen_launcher_icons.py -->
"""
TAIL = "</vector>\n"


def fmt(v):
    return f"{v:g}"


def pixels(cells):
    x0, y0 = ORIGIN
    return "".join(f"M{x0 + c * UNIT},{y0 + r * UNIT} h{PIXEL} v{PIXEL} h-{PIXEL} Z " for c, r in cells).strip()


def path(data, color, halo):
    # A faint outline in the same colour: the glow of the CRT style, kept subtle at icon size.
    glow = f' android:strokeColor="{color}" android:strokeWidth="2" android:strokeAlpha="0.28"' if halo else ""
    return f'        <path android:pathData="{data}" android:fillColor="{color}"{glow} />\n'


def icon(letter, cursor, halo=True):
    art = path(pixels(STEM + SHOULDER + LEG), letter, halo) + path(pixels([CURSOR]), cursor, halo)
    return (
        HEAD
        + f'    <group android:pivotX="54" android:pivotY="54" android:scaleX="{fmt(SCALE)}" android:scaleY="{fmt(SCALE)}" '
        f'android:translateY="{fmt(SHIFT_Y)}">\n{art}    </group>\n'
        + TAIL
    )


def adaptive(fg, bg):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <background android:drawable="{bg}" />\n'
        f'    <foreground android:drawable="@drawable/{fg}" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )


def camel(icon_id):
    return "".join(part.capitalize() for part in icon_id.split("_"))


def main():
    palettes = [
        dict(zip(("id", "name", "bg", "surface", "border", "text", "dim", "primary", "action", "soft", "warn"), m))
        for m in PALETTE.findall(THEME.read_text())
    ]
    assert palettes, "no palettes found in Theme.kt"
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi").mkdir(parents=True, exist_ok=True)

    # Start clean: icons that no longer exist must not linger.
    for pattern, folder in (("ic_launcher_fg_*.xml", "drawable"), ("ic_launcher_*.xml", "mipmap-anydpi")):
        for f in (RES / folder).glob(pattern):
            f.unlink()

    colors = ["<resources>", "    <!-- generated by tools/gen_launcher_icons.py -->"]
    ids = []
    for p in palettes:
        i = p["id"]
        (RES / f"drawable/ic_launcher_fg_{i}.xml").write_text(icon("#" + p["primary"], "#" + p["action"]))
        (RES / f"mipmap-anydpi/ic_launcher_{i}.xml").write_text(adaptive(f"ic_launcher_fg_{i}", f"@color/ic_launcher_bg_{i}"))
        colors.append(f'    <color name="ic_launcher_bg_{i}">#{p["bg"]}</color>')
        ids.append(i)
    colors.append("</resources>")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(icon("#FFFFFF", "#FFFFFF", halo=False))
    (RES / "values/launcher_colors.xml").write_text("\n".join(colors) + "\n")

    aliases = []
    for i in ids:
        enabled = "true" if i == DEFAULT else "false"
        aliases.append(
            f'        <activity-alias\n            android:name=".Launcher{camel(i)}"\n            android:enabled="{enabled}"\n'
            f'            android:exported="true"\n            android:icon="@mipmap/ic_launcher_{i}"\n'
            '            android:label="@string/app_name"\n            android:targetActivity=".MainActivity">\n'
            '            <intent-filter>\n                <action android:name="android.intent.action.MAIN" />\n'
            '                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n'
            "        </activity-alias>"
        )
    begin, end = "<!-- BEGIN launcher aliases (tools/gen_launcher_icons.py) -->", "<!-- END launcher aliases -->"
    block = f"        {begin}\n" + "\n".join(aliases) + f"\n        {end}\n"
    m = MANIFEST.read_text()
    if begin in m:
        m = re.sub(re.escape("        " + begin) + r".*?" + re.escape(end) + r"\n", lambda _: block, m, flags=re.S)
    else:
        m = m.replace("    </application>", block + "    </application>")
    MANIFEST.write_text(m)
    print("generated icons for:", ", ".join(ids))


if __name__ == "__main__":
    main()
